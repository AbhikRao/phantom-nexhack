/**
 * backendGenerator — turns an inferred contract into a standalone, runnable TypeScript backend project.
 *
 * Deterministic templates only. Handler code is copied verbatim from templates/backend; the only generated source is
 * src/resources.ts, whose values are emitted through JSON.stringify and whose identifiers derive from resource names
 * that already passed a strict ^[a-z][a-z0-9_-]{0,39}$ check. Observed strings are never spliced into code unescaped.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zipSync, strToU8 } from 'fflate';
import type { InferredContract, TypeNode } from './contractInference.ts';
import { buildOpenApi, isSafeFieldName } from './contractInference.ts';
import type { EngineSnapshot } from './resourceEngine.ts';
import { RESOURCE_NAME } from './resourceEngine.ts';

const TEMPLATE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../templates/backend');
const TEMPLATE_FILES = ['src/server.ts', 'src/store.ts', 'src/validate.ts', 'test/crud.test.ts', 'tsconfig.json'];

/** Exact source line the mutation test sabotages (PATCH stops applying the request body). */
export const PATCH_MERGE_LINE = "const merged = method === 'PATCH' ? { ...userFields(existing), ...patch } : { ...patch };";
const PATCH_MUTANT_LINE = "const merged = method === 'PATCH' ? { ...userFields(existing) } : { ...patch }; // MUTANT: PATCH ignores body";

export type Mutation = 'patch-ignores-body';

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface BuildInfo {
  id: string;
  createdAt: string;
  dir: string;
  resources: string[];
  traceCount: number;
  seedRecords: number;
  mutation?: Mutation;
  files: { path: string; bytes: number; sha256: string }[];
}

export interface GenerateOptions {
  buildId: string;
  /** Current emulator dataset, exported as seed.json so the REAL backend can start with the same data. */
  seed?: EngineSnapshot;
  mutation?: Mutation;
  createdAt?: string;
}

const PRIMITIVES = new Set(['string', 'integer', 'number', 'boolean', 'null', 'object', 'array']);

/** Copy a type node keeping only known primitive names and safe field names (defence in depth). */
interface CleanNode {
  types: TypeNode['types'];
  properties?: Record<string, CleanNode>;
  items?: CleanNode;
}

function cleanNode(node: TypeNode, depth = 0): CleanNode {
  const out: CleanNode = { types: node.types.filter((t) => PRIMITIVES.has(t)) };
  if (depth > 8) return out;
  if (node.properties) {
    out.properties = {};
    for (const [k, v] of Object.entries(node.properties)) if (isSafeFieldName(k)) out.properties[k] = cleanNode(v, depth + 1);
  }
  if (node.items) out.items = cleanNode(node.items, depth + 1);
  return out;
}

function tsType(node: CleanNode, depth = 0): string {
  if (node.types.length === 0) return 'unknown';
  const parts = node.types.map((t) => {
    switch (t) {
      case 'string':
        return 'string';
      case 'integer':
      case 'number':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array':
        return node.items && node.items.types.length && depth < 6 ? `Array<${tsType(node.items, depth + 1)}>` : 'unknown[]';
      case 'object':
        if (!node.properties || depth >= 6 || Object.keys(node.properties).length === 0) return 'Record<string, unknown>';
        return `{ ${Object.entries(node.properties)
          .map(([k, v]) => `${JSON.stringify(k)}?: ${tsType(v, depth + 1)}`)
          .join('; ')} }`;
    }
    return 'unknown';
  });
  return [...new Set(parts)].join(' | ');
}

function pascal(name: string): string {
  return name
    .split(/[-_]/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

export function renderResourcesTs(contract: InferredContract, buildId: string): string {
  const lines: string[] = [
    `// GENERATED by PHANTOM from ${contract.traceCount} recorded HTTP interactions (${contract.generatedAt}).`,
    '// Field types and required fields were inferred deterministically from observed traffic. Regenerate rather than editing.',
    "import type { ResourceSchema } from './validate.ts';",
    '',
    `export const BUILD_ID = ${JSON.stringify(buildId)};`,
    '',
  ];
  const schemas: Record<string, { fields: Record<string, CleanNode>; required: string[] }> = {};
  for (const r of contract.resources) {
    if (!RESOURCE_NAME.test(r.name)) continue;
    const fields: Record<string, CleanNode> = {};
    for (const [k, v] of Object.entries(r.fields)) if (isSafeFieldName(k)) fields[k] = cleanNode(v);
    schemas[r.name] = { fields, required: r.required.filter((k) => Object.hasOwn(fields, k)) };
    const iface = `${pascal(r.name)}Record`;
    lines.push(`/** A record in /api/${r.name} (${r.createCount} create request(s) observed). */`);
    lines.push(`export interface ${iface} {`);
    lines.push('  "id": number;');
    for (const [k, v] of Object.entries(fields)) {
      lines.push(`  ${JSON.stringify(k)}${schemas[r.name].required.includes(k) ? '' : '?'}: ${tsType(v)};`);
    }
    lines.push('  "createdAt": string;', '  "updatedAt": string;', '  [extra: string]: unknown;', '}', '');
  }
  lines.push(`export const RESOURCES: Record<string, ResourceSchema> = ${JSON.stringify(schemas, null, 2)};`, '');
  return lines.join('\n');
}

function renderReadme(contract: InferredContract, buildId: string, seedRecords: number): string {
  const rows = contract.resources
    .filter((r) => RESOURCE_NAME.test(r.name))
    .map((r) => {
      const fields = Object.entries(r.fields)
        .filter(([k]) => isSafeFieldName(k))
        .map(([k, v]) => `\`${k.replace(/[`|\\]/g, '')}\`${r.required.includes(k) ? '*' : ''}: ${v.types.join(' \\| ')}`)
        .join(', ');
      return `| \`/api/${r.name}\` | ${fields || '_no fields observed_'} |`;
    })
    .join('\n');
  return `# Generated backend (build ${buildId})

This project was generated by **PHANTOM** from ${contract.traceCount} recorded HTTP interactions.
It is a standalone server: it never contacts PHANTOM and has **zero runtime dependencies**
(\`node:http\` + the built-in \`node:sqlite\` module).

## Run

Requires **Node.js 22.18+** (TypeScript is executed directly via Node's built-in type stripping).

\`\`\`bash
npm start                    # http://127.0.0.1:8788, data in ./data/phantom.db
PORT=9000 DATA_DIR=./db npm start
SEED_FILE=seed.json npm start   # import the dataset exported from PHANTOM (only when the database is empty)
\`\`\`

Optional checks (need \`npm install\` for the TypeScript dev dependency):

\`\`\`bash
npm run typecheck
npm test                     # spawns the server on an ephemeral port, CRUD + restart persistence
\`\`\`

## Endpoints

\`GET /health\` reports status, build id, database path and record counts.

| Collection | Inferred fields (* = required on create) |
|---|---|
${rows || '| _none_ | |'}

For every collection: \`GET /api/x\` (array, exact-match query filters such as \`?status=done\`), \`POST /api/x\` (201),
\`GET|PATCH|PUT|DELETE /api/x/:id\` (200 / 204, 404 when missing). PATCH shallow-merges, PUT replaces client fields.
\`id\`, \`createdAt\` and \`updatedAt\` are server-managed. Invalid JSON, non-object bodies and type mismatches against the
inferred contract return 400 with \`{ error, message }\`. Unknown collections return 404.

See \`openapi.json\` for the full OpenAPI 3.1 document.

## Configuration

| Variable | Default | Purpose |
|---|---|---|
| PORT | 8788 | Listen port (0 = ephemeral) |
| HOST | 127.0.0.1 | Bind address |
| DATA_DIR | ./data | SQLite database directory |
| SEED_FILE | — | JSON dataset imported once into an empty database (\`seed.json\` holds ${seedRecords} record(s)) |
| CORS_ORIGINS | localhost:8787, localhost:5173 | Comma-separated allowed browser origins |
| MAX_BODY_BYTES | 1048576 | Request body limit |

## Limitations

Only the REST structure and JSON types visible in recorded traffic are reproduced. Authentication, authorization,
relationships between collections, uniqueness constraints and other business rules were **not** inferred and must be added
by an engineer.
`;
}

export function generateProject(contract: InferredContract, options: GenerateOptions): GeneratedFile[] {
  if (!/^[a-z0-9-]{1,64}$/.test(options.buildId)) throw new Error('invalid build id');
  const resources = contract.resources.filter((r) => RESOURCE_NAME.test(r.name)).map((r) => r.name);
  const seedCollections: Record<string, unknown[]> = {};
  let seedRecords = 0;
  for (const name of resources) {
    const records = options.seed?.collections[name]?.records ?? [];
    seedCollections[name] = records;
    seedRecords += records.length;
  }
  const files: GeneratedFile[] = [];
  for (const rel of TEMPLATE_FILES) {
    let content = readFileSync(join(TEMPLATE_DIR, rel), 'utf8');
    if (rel === 'src/server.ts' && options.mutation === 'patch-ignores-body') {
      if (!content.includes(PATCH_MERGE_LINE)) throw new Error('mutation target not found in template');
      content = content.replace(PATCH_MERGE_LINE, PATCH_MUTANT_LINE);
    }
    files.push({ path: rel, content });
  }
  files.push({ path: 'src/resources.ts', content: renderResourcesTs(contract, options.buildId) });
  files.push({
    path: 'package.json',
    content:
      JSON.stringify(
        {
          name: 'phantom-generated-backend',
          version: '1.0.0',
          private: true,
          description: `REST backend generated by PHANTOM (build ${options.buildId})`,
          type: 'module',
          engines: { node: '>=22.18' },
          scripts: {
            start: 'node --disable-warning=ExperimentalWarning src/server.ts',
            test: 'node --disable-warning=ExperimentalWarning --test test/crud.test.ts',
            typecheck: 'tsc -p tsconfig.json',
          },
          devDependencies: { typescript: '^7.0.2', '@types/node': '^24.0.0' },
        },
        null,
        2,
      ) + '\n',
  });
  files.push({ path: 'openapi.json', content: JSON.stringify(buildOpenApi(contract, { title: 'Generated backend' }), null, 2) + '\n' });
  files.push({ path: 'seed.json', content: JSON.stringify({ exportedAt: options.createdAt ?? new Date().toISOString(), collections: seedCollections }, null, 2) + '\n' });
  files.push({ path: 'README.md', content: renderReadme(contract, options.buildId, seedRecords) });
  files.push({ path: '.gitignore', content: 'node_modules/\ndata/\n' });
  files.push({ path: '.env.example', content: 'PORT=8788\nHOST=127.0.0.1\nDATA_DIR=./data\n# SEED_FILE=seed.json\nCORS_ORIGINS=http://127.0.0.1:8787,http://localhost:8787\n' });
  const manifest = {
    generator: 'phantom',
    buildId: options.buildId,
    createdAt: options.createdAt ?? new Date().toISOString(),
    traceCount: contract.traceCount,
    resources,
    mutation: options.mutation ?? null,
    files: files.map((f) => ({ path: f.path, sha256: sha256(f.content) })),
  };
  files.push({ path: 'PHANTOM_MANIFEST.json', content: JSON.stringify(manifest, null, 2) + '\n' });
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

function sha256(s: string): string {
  return createHash('sha256').update(s).digest('hex');
}

/** Write files below `dir`, refusing any path that would escape it. */
export function writeProject(dir: string, files: GeneratedFile[]): void {
  const root = resolve(dir);
  for (const f of files) {
    const target = resolve(root, f.path);
    const rel = relative(root, target);
    if (rel.startsWith('..') || rel.includes(`..${sep}`) || resolve(root, rel) !== target || f.path.includes('\0')) {
      throw new Error(`refusing to write outside build directory: ${f.path}`);
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, f.content);
  }
}

export function zipProject(files: GeneratedFile[], folder = 'phantom-generated-backend'): Uint8Array {
  const entries: Record<string, Uint8Array> = {};
  for (const f of files) entries[`${folder}/${f.path}`] = strToU8(f.content);
  return zipSync(entries, { level: 6, mtime: new Date('2026-11-03T00:00:00Z') });
}

export function describeBuild(id: string, dir: string, contract: InferredContract, files: GeneratedFile[], options: GenerateOptions): BuildInfo {
  const seed = files.find((f) => f.path === 'seed.json');
  const seedRecords = seed ? Object.values((JSON.parse(seed.content) as { collections: Record<string, unknown[]> }).collections).reduce((n, a) => n + a.length, 0) : 0;
  return {
    id,
    createdAt: options.createdAt ?? new Date().toISOString(),
    dir,
    resources: contract.resources.filter((r) => RESOURCE_NAME.test(r.name)).map((r) => r.name),
    traceCount: contract.traceCount,
    seedRecords,
    mutation: options.mutation,
    files: files.map((f) => ({ path: f.path, bytes: Buffer.byteLength(f.content), sha256: sha256(f.content) })),
  };
}
